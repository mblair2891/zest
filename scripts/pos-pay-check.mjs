import { chromium } from "playwright";
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1400, height: 900 } });
await page.goto("http://127.0.0.1:8080/");
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: "networkidle" });
await page.waitForTimeout(700);
await page.getByRole("button", { name: /Jordan Lee/i }).click();
await page.waitForTimeout(700);
await page.locator("button").filter({ hasText: "2 top" }).first().click();
await page.getByRole("button", { name: /Seat party/i }).click();
await page.waitForTimeout(600);
await page.getByRole("button", { name: /Beer/i }).click();
await page.getByRole("button", { name: /Harbor Lager/i }).click();
await page.waitForTimeout(200);
await page.getByRole("button", { name: /^Send$/i }).click();
await page.waitForTimeout(300);
const payLabel = await page.getByRole("button", { name: /Pay/i }).innerText();
console.log("pay button", payLabel);
await page.getByRole("button", { name: /Pay/i }).click();
await page.waitForTimeout(400);
const bal = await page.locator("text=Balance due").locator("..").innerText();
console.log("dialog", bal);
await page.getByRole("button", { name: /Charge card/i }).click();
await page.waitForTimeout(500);
console.log("after pay", await page.locator("[role=dialog]").innerText().catch(() => "no dialog"));
await page.getByRole("button", { name: /^Done$/i }).click().catch(() => {});
await page.waitForTimeout(400);
await page.locator("nav button", { hasText: "Reports" }).first().click();
await page.waitForTimeout(700);
console.log("reports", (await page.locator("main").innerText()).slice(0, 400));
const state = await page.evaluate(() => {
  const raw = localStorage.getItem("harbor-hearth-pos-v1");
  if (!raw) return null;
  const d = JSON.parse(raw).state;
  return { shift: d.shift, orders: d.orders.map(o => ({n:o.number,status:o.status,pay:o.payments})) };
});
console.log(JSON.stringify(state, null, 2));
await browser.close();
